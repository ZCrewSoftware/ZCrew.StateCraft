namespace ZCrew.StateCraft.PlantUml;

/// <summary>
///     The layout direction PlantUML uses when rendering the state diagram.
/// </summary>
public enum PlantUmlDirection
{
    /// <summary>
    ///     States flow from the top of the diagram to the bottom.
    /// </summary>
    TopToBottom,

    /// <summary>
    ///     States flow from the left of the diagram to the right.
    /// </summary>
    LeftToRight,
}
